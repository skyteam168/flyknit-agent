const dicts: Record<string, Dict> = { 'zh-CN': zh, 'vi-VN': vi, 'en-US': en }

let current: Dict = zh

export function setLanguage(lang: string) {
  current = dicts[lang] ?? (lang.startsWith('vi') ? vi : lang.startsWith('en') ? en : zh)
  document.documentElement.lang = lang
}

export function t(key: keyof Dict, ...args: string[]): string {
  return args.reduce((s, a, i) => s.replace(`{${i}}`, a), current[key])
}
